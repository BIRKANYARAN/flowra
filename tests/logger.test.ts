/**
 * Tests for lib/logger.ts — pure exported functions only.
 *
 * Functions tested:
 *   shouldLog(level)              — level rank filtering
 *   makeRequestContext(userId?)   — generates a UUID-format requestId
 *   contextFromHeader(header, userId?) — uses or generates request context
 *   createTimer(label)            — high-resolution timer returning { end() }
 *   serializeError(err)           — serialize any caught value to structured log object
 *
 * The async log() function writes to Supabase RPC and is NOT tested here.
 *
 * Run with: npx vitest run tests/logger.test.ts
 */
